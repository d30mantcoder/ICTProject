function translateValue(value,previous,catalog){
 let source=previous?.rendered===value?previous.source:value;
 if(previous?.rendered!==value){
  const trimmed=source.trim();
  if(!catalog.forward.has(trimmed)&&catalog.reverse.has(trimmed))source=source.replace(trimmed,catalog.reverse.get(trimmed));
  else if(!catalog.forward.has(trimmed)){
   for(const [ru,en] of catalog.prefixes){if(source.startsWith(en)){source=ru+source.slice(en.length);break}}
  }
 }
 const trimmed=source.trim();
 let rendered=source;
 if(uiLanguage==='en'){
  if(catalog.forward.has(trimmed))rendered=source.replace(trimmed,catalog.forward.get(trimmed));
  else if(UI_EN[source])rendered=UI_EN[source];
  else for(const [ru,en] of catalog.prefixes){if(source.startsWith(ru)){rendered=en+source.slice(ru.length);break}}
 }
 return {source,rendered};
}

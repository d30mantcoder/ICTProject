 function text(node){
  if(!node.parentElement||node.parentElement.closest(uiExcluded))return;
  const result=translateValue(node.nodeValue,uiTextSources.get(node),catalog);
  uiTextSources.set(node,result);if(node.nodeValue!==result.rendered)node.nodeValue=result.rendered;
 }
